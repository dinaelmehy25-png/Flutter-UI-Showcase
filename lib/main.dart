import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:provider/provider.dart';

import 'firebase_options.dart'; // generated by: flutterfire configure
import 'services/auth_service.dart';
import 'services/remote_config_service.dart';
import 'viewmodels/auth_viewmodel.dart';
import 'viewmodels/config_viewmodel.dart';
import 'views/auth_gate.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // 1. Connect the app to your Firebase project.
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

  // 2. Load Remote Config values before the first screen appears.
  final remoteConfigService = RemoteConfigService();
  await remoteConfigService.init();

  runApp(MyApp(remoteConfigService: remoteConfigService));
}

class MyApp extends StatelessWidget {
  const MyApp({super.key, required this.remoteConfigService});

  final RemoteConfigService remoteConfigService;

  @override
  Widget build(BuildContext context) {
    // 3. Make the ViewModels available to every View.
    return MultiProvider(
      providers: [
        ChangeNotifierProvider(create: (_) => AuthViewModel(AuthService())),
        ChangeNotifierProvider(create: (_) => ConfigViewModel(remoteConfigService)),
      ],
      child: MaterialApp(
        title: 'Firebase MVVM Demo',
        debugShowCheckedModeBanner: false,
        theme: ThemeData(
          useMaterial3: true,
          colorSchemeSeed: const Color(0xFF2E5E4E),
          inputDecorationTheme: const InputDecorationTheme(
            border: OutlineInputBorder(),
          ),
        ),
        home: const AuthGate(),
      ),
    );
  }
}
